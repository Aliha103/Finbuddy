#!/usr/bin/env node
/**
 * Rasterises the brand SVGs in apps/mobile/assets/brand into the PNGs app.json needs, with sharp
 * (root devDependency, exact version). Run from the repo root: `npm run brand:icons`.
 *
 * Every output is listed in apps/mobile/assets/brand/RASTERS.md with its source, size and SHA-256,
 * so each shipping raster carries its provenance. Re-running produces identical files.
 */
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import sharp from 'sharp';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const brand = join(root, 'apps/mobile/assets/brand');
const assets = join(root, 'apps/mobile/assets');

/** source svg (in assets/brand) -> output png (in assets), rendered width and height. */
const JOBS = [
  { src: 'icon-ios-light.svg', out: 'icon.png', width: 1024, height: 1024, note: 'iOS app icon, light; also the Expo default icon' },
  { src: 'icon-ios-dark.svg', out: 'icon-dark.png', width: 1024, height: 1024, note: 'iOS 18 dark appearance (transparent ground)' },
  { src: 'icon-ios-tinted.svg', out: 'icon-tinted.png', width: 1024, height: 1024, note: 'iOS 18 tinted appearance (greyscale glyph)' },
  { src: 'android-foreground.svg', out: 'android-icon-foreground.png', width: 1024, height: 1024, note: 'Android adaptive icon, foreground layer (108 dp canvas)' },
  { src: 'android-background.svg', out: 'android-icon-background.png', width: 1024, height: 1024, note: 'Android adaptive icon, background layer (flat Graphite)' },
  { src: 'android-monochrome.svg', out: 'android-icon-monochrome.png', width: 1024, height: 1024, note: 'Android 13+ themed icon layer' },
  { src: 'splash-icon.svg', out: 'splash-icon.png', width: 800, height: 520, note: 'Splash image: the three bars, placed on graphite by expo-splash-screen' },
  { src: 'mark.svg', out: 'favicon.png', width: 64, height: 64, note: 'Web favicon (the mark)' },
];

mkdirSync(assets, { recursive: true });
const rows = [];
for (const job of JOBS) {
  const svg = readFileSync(join(brand, job.src));
  // density: sharp rasterises SVG at 72 dpi by default; ask for the exact pixel size instead.
  const png = await sharp(svg, { density: 72 })
    .resize(job.width, job.height, { fit: 'fill' })
    .png({ compressionLevel: 9, adaptiveFiltering: false, palette: false })
    .toBuffer();
  const outPath = join(assets, job.out);
  writeFileSync(outPath, png);
  const meta = await sharp(png).metadata();
  rows.push({ ...job, bytes: png.length, sha256: createHash('sha256').update(png).digest('hex'), alpha: meta.hasAlpha });
  console.log(`${relative(root, outPath)}  ${meta.width}x${meta.height}  ${png.length} bytes`);
}

const lines = [
  '# Brand rasters',
  '',
  'Generated by `scripts/render-icons.mjs` (sharp ' + sharp.versions.sharp + ', libvips ' + sharp.versions.vips + ', librsvg ' + sharp.versions.rsvg + ') from the SVG sources in this folder.',
  'Do not edit the PNGs by hand: change the SVG, then run `npm run brand:icons` from the repo root.',
  '',
  '| Output (apps/mobile/assets) | Source | Size | Alpha | Bytes | SHA-256 | Use |',
  '|---|---|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.out} | brand/${r.src} | ${r.width}x${r.height} | ${r.alpha ? 'yes' : 'no'} | ${r.bytes} | ${r.sha256} | ${r.note} |`),
  '',
  'Vector sources that are used directly (never rasterised here): `mark.svg`, `wordmark.svg`, `lockup.svg`; the app draws them with react-native-svg (`src/design/Brand.tsx`).',
  '',
];
writeFileSync(join(brand, 'RASTERS.md'), lines.join('\n'));
console.log(`wrote ${relative(root, join(brand, 'RASTERS.md'))}`);
